CREATE TABLE IF NOT EXISTS public.product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS public.route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path VARCHAR(255) NOT NULL UNIQUE,
    target_url VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);

GRANT CONNECT ON DATABASE postgres TO gateway_app, backend_app;
GRANT USAGE ON SCHEMA public TO gateway_app, backend_app;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.route, public.users TO gateway_app;

GRANT USAGE, SELECT
    ON SEQUENCE public.route_id_seq, public.users_id_seq TO gateway_app;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.product TO backend_app;

GRANT USAGE, SELECT
    ON SEQUENCE public.product_id_seq TO backend_app;
